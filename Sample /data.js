export function parseDMY(s) {
  if (!s) return null;
  const p = String(s).split("/");
  if (p.length === 3) return new Date(+p[2], +p[1] - 1, +p[0]);
  return new Date(s);
}

export function daysTo(d) {
  const e = parseDMY(d);
  if (!e) return 999;
  return Math.round((e - TODAY) / 86400000);
}
